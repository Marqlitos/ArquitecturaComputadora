;CODIGO ORIGINAL 

ORG 100h

.DATA
    ARREGLO DW 10h, 20h, 30h, 40h
    RESULTADO DW 0
    
.CODE
MAIN:
    MOV AX, @DATA
    MOV DS, AX
    
    CALL PROCESAR_DATOS  ;SALVA IP DE ENTORNO EN LA PILA
    MOV RESULTADO, AX
    RET

PROCESAR_DATOS PROC   ;SALVA IP  DE RETORNO EN LA PILA
    PUSH CX ;RESGUARDA CX EN LA PILA (2 BYTES)
    MOV AX, [ARREGLO] ;SOLO LEE EL PRIMER ELEMENTO
    
    MOV CX, [ARREGLO+2]  ;SUMA ACTUAL RIGIDA
    ADD AX, CX
    
    PUSH AX ;ERROR: GUARDA AX EN LA PILA Y NO LO RETIRA
    POP CX  ;RECUPERA CX
   
RET ;ERROR CRITICO: RET SACA EL VALOR DE AX 
PROCESAR_DATOS ENDP
END  MAIN