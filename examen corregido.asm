; CODIGO CORREGIDO Y OPTIMIZADO

ORG 100h

.DATA
    ARREGLO DW 10h, 20h, 30h, 40h
    RESULTADO DW 0

.CODE
MAIN:
    MOV AX, @DATA
    MOV DS, AX

    CALL PROCESAR_DATOS ;SALVA IP DE ENTORNO EN LA PILA
    MOV RESULTADO, AX
    MOV AH, 4Ch
    INT 21h

PROCESAR_DATOS PROC      ;SALVA IP  DE RETORNO EN LA PILA
    PUSH CX     ;RESGUARDA CX EN LA PILA (2 BYTES)
    PUSH SI
    XOR AX, AX          ; AX = 0
    XOR SI, SI          ; SI = 0
    MOV CX, 4           ; Cantidad de elementos

SUMAR:
    ADD AX, [ARREGLO + SI] ;SUMA ACTUAL RIGIDA
    ADD SI, 2
    LOOP SUMAR
    POP SI
    POP CX  ;RECUPERA CX
    RET
PROCESAR_DATOS ENDP
END MAIN